export type TranslationKey = keyof typeof translations.fr;

export function getTranslation(locale: string, key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = (translations as Record<string, typeof translations.fr>)[locale] || translations.fr;
  let text = (dict as Record<string, string | string[]>)[key] as string;
  if (!text) {
    text = (translations.fr as Record<string, string | string[]>)[key] as string;
  }
  if (params && typeof text === 'string') {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text || key;
}
